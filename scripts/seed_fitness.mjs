function generateFitnessSeed() {
  if (!fs.existsSync(DATA_DIR)) fs.mkdirSync(DATA_DIR, { recursive: true });

  // Normalizar para 100g/100ml padrão
  const normalized = FITNESS_FOODS.map((f, idx) => {
    const factor = 100.0 / f.base_qty;
    const novaClassification = classifyNovaGroup(f.name, f.category);
    return {
      name: f.name,
      brand: f.brand,
      category: f.category,
      unit_type: f.unit_type,
      base_qty: 100.0,
      serving_description: f.serving_description,
      calories: Math.round(f.calories * factor * 10) / 10,
      protein_g: Math.round(f.protein_g * factor * 10) / 10,
      carbs_g: Math.round(f.carbs_g * factor * 10) / 10,
      fats_g: Math.round(f.fats_g * factor * 10) / 10,
      saturated_fats_g: Math.round(f.saturated_fats_g * factor * 10) / 10,
      monounsaturated_fats_g: Math.round(f.monounsaturated_fats_g * factor * 10) / 10,
      polyunsaturated_fats_g: Math.round(f.polyunsaturated_fats_g * factor * 10) / 10,
      trans_fats_g: Math.round(f.trans_fats_g * factor * 10) / 10,
      cholesterol_mg: Math.round(f.cholesterol_mg * factor * 10) / 10,
      fiber_g: Math.round(f.fiber_g * factor * 10) / 10,
      sodium_mg: Math.round(f.sodium_mg * factor * 10) / 10,
      source: 'verified',
      source_id: `FIT_${idx + 1}`,
      is_incomplete: false,
      nova_group: novaClassification.group,
    };
  });

  fs.writeFileSync(FITNESS_JSON_FILE, JSON.stringify(normalized, null, 2), 'utf-8');
  console.log(`✓ JSON Fitness salvo em: ${FITNESS_JSON_FILE} (${normalized.length} itens curados com classificação NOVA).`);

  let sql = `-- SEED FITNESS & SUPLEMENTAÇÃO NACIONAL CURADA COM CLASSIFICAÇÃO NOVA
-- Categoria: verified (Whey, Creatina, Barras, Bebidas Proteicas) & Guia Alimentar (MS)
`;
  sql += `INSERT INTO public.foods_master (name, brand, category, unit_type, base_qty, serving_description, calories, protein_g, carbs_g, fats_g, saturated_fats_g, monounsaturated_fats_g, polyunsaturated_fats_g, trans_fats_g, cholesterol_mg, fiber_g, sodium_mg, source, source_id, is_incomplete, nova_group)\nVALUES\n`;

  const values = normalized.map((f) => {
    const escName = f.name.replace(/'/g, "''");
    const escBrand = f.brand ? `'${f.brand.replace(/'/g, "''")}'` : 'NULL';
    const escCat = f.category.replace(/'/g, "''");
    const escServ = f.serving_description.replace(/'/g, "''");
    return `  ('${escName}', ${escBrand}, '${escCat}', '${f.unit_type}', 100.0, '${escServ}', ${f.calories}, ${f.protein_g}, ${f.carbs_g}, ${f.fats_g}, ${f.saturated_fats_g}, ${f.monounsaturated_fats_g}, ${f.polyunsaturated_fats_g}, ${f.trans_fats_g}, ${f.cholesterol_mg}, ${f.fiber_g}, ${f.sodium_mg}, 'verified', '${f.source_id}', false, ${f.nova_group})`;
  });

  sql += values.join(',\n') + '\nON CONFLICT DO NOTHING;\n\n';
  fs.writeFileSync(FITNESS_SEED_SQL, sql, 'utf-8');
  console.log(`✓ Script SQL Fitness salvo em: ${FITNESS_SEED_SQL}`);
}

generateFitnessSeed();
